import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import BUILTIN_1192 from '../src/builtin1192.js';
import { parseHoi4Localization } from '../src/ui-localization.js';

const sourceRoot=process.argv[2];
const outputPath=process.argv[3]||'src/builtin1192/localization-english-1192.js';
if(!sourceRoot){
  console.error('Usage: node scripts/build-localization-map.mjs <extracted localisation/english folder> [output file]');
  process.exit(2);
}

async function walk(dir){
  const out=[];
  for(const entry of await readdir(dir,{withFileTypes:true})){
    const full=path.join(dir,entry.name);
    if(entry.isDirectory())out.push(...await walk(full));
    else if(entry.isFile()&&/\.ya?ml$/i.test(entry.name))out.push(full);
  }
  return out;
}

function stableObject(entries){
  return Object.fromEntries([...entries].sort(([a],[b])=>a.localeCompare(b)));
}

const files=(await walk(sourceRoot)).sort((a,b)=>a.localeCompare(b));
const localization={};
const corpusHash=createHash('sha256');
for(const file of files){
  const bytes=await readFile(file),rel=path.relative(sourceRoot,file).replaceAll('\\','/');
  corpusHash.update(rel);corpusHash.update('\0');corpusHash.update(bytes);corpusHash.update('\0');
  const parsed=parseHoi4Localization(bytes.toString('utf8'),{language:'english'});
  Object.assign(localization,parsed.entries);
}

const targets=new Map();
const add=(group,id,record={})=>{
  const key=String(id||'').trim();if(!key)return;
  const raw=record?.raw||{};
  const candidates=[
    record?.localizationKey,record?.localisationKey,record?.nameKey,record?.name,
    raw?.localization_key,raw?.localisation_key,raw?.name,raw?.variant_name,raw?.derived_variant_name,
    key,`${key}_name`,`${key}_NAME`,`${key}_title`,`${key}_TITLE`
  ].filter(value=>typeof value==='string'&&value.trim()).map(value=>value.trim());
  const previous=targets.get(key);
  targets.set(key,{group,candidates:[...new Set([...(previous?.candidates||[]),...candidates])]});
};

for(const group of ['subUnits','equipment','modules','mios','technologies','doctrines','doctrineMetadata','combatTactics','terrain','modifiers','specialProjects','duplicateArchetypes']){
  for(const [id,record] of Object.entries(BUILTIN_1192?.[group]||{}))add(group,id,record);
}
for(const [mioId,mio] of Object.entries(BUILTIN_1192?.mios||{})){
  for(const [traitId,trait] of Object.entries(mio?.traits||{}))add(`mios.${mioId}.traits`,traitId,trait);
}

function resolveStaticReference(value,seen=new Set()){
  let current=String(value??'').trim();
  for(let depth=0;depth<8;depth++){
    const match=current.match(/^\$([A-Za-z0-9_.:-]+)\$$/);
    if(!match)return current;
    const key=match[1];if(seen.has(key)||typeof localization[key]!=='string')return '';
    seen.add(key);current=String(localization[key]).trim();
  }
  return '';
}

const resolved=new Map(),sourceKeys=new Map(),unresolved=[];
for(const [id,target] of [...targets.entries()].sort(([a],[b])=>a.localeCompare(b))){
  let found='';
  for(const candidate of target.candidates){
    const raw=localization[candidate];if(typeof raw!=='string'||!raw.trim())continue;
    const value=resolveStaticReference(raw);if(!value||/\$[^$]+\$/.test(value))continue;
    found=candidate;resolved.set(id,value);sourceKeys.set(id,candidate);break;
  }
  if(!found)unresolved.push({id,group:target.group,candidates:target.candidates});
}

const generatedAt=new Date().toISOString();
const meta={
  gameVersion:'1.19.2',language:'english',source:'HOI4 localisation/english',generated:true,generatedAt,
  sourceFileCount:files.length,sourceDigestSha256:corpusHash.digest('hex'),targetCount:targets.size,
  resolvedCount:resolved.size,unresolvedCount:unresolved.length
};
const body=`/* Generated by scripts/build-localization-map.mjs from an authoritative HOI4 1.19.2 localisation/english corpus. */\n\nexport const BUILTIN_ENGLISH_LOCALIZATION_1192_META=Object.freeze(${JSON.stringify(meta,null,2)});\n\nexport const BUILTIN_ENGLISH_LOCALIZATION_1192_SOURCE_KEYS=Object.freeze(${JSON.stringify(stableObject(sourceKeys),null,2)});\n\nexport const BUILTIN_ENGLISH_LOCALIZATION_1192=Object.freeze(${JSON.stringify(stableObject(resolved),null,2)});\n\nexport default BUILTIN_ENGLISH_LOCALIZATION_1192;\n`;
await writeFile(outputPath,body,'utf8');
console.log(`Generated ${resolved.size}/${targets.size} source-backed English labels from ${files.length} files.`);
if(unresolved.length){
  const report=`${outputPath}.unresolved.json`;
  await writeFile(report,JSON.stringify({meta,unresolved},null,2)+'\n','utf8');
  console.log(`Unresolved target report: ${report}`);
}
